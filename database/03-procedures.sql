/* ------------------------------------------------------------
   List the catalogue with its next scheduled session.
   OUTER APPLY keeps it one round trip instead of N+1 probes.
   ------------------------------------------------------------ */
CREATE OR ALTER PROCEDURE dbo.usp_Workshop_List
AS
BEGIN
    SET NOCOUNT ON;

    SELECT  w.Id,
            w.Slug,
            w.Code,
            w.Title,
            w.Summary,
            w.Audience,
            w.Level,
            w.PriceMyr,
            w.PriceNote,
            w.DurationDays,
            w.IsFeatured,
            w.Accent,
            nxt.StartsOn  AS NextStartsOn,
            nxt.EndsOn    AS NextEndsOn,
            nxt.City      AS NextCity,
            nxt.SeatsLeft AS NextSeatsLeft
    FROM    dbo.Workshops AS w
    OUTER APPLY
            (
                SELECT TOP (1) s.StartsOn, s.EndsOn, s.City, s.SeatsLeft
                FROM   dbo.WorkshopSessions AS s
                WHERE  s.WorkshopId = w.Id
                  AND  s.StartsOn  >= CAST(SYSUTCDATETIME() AS DATE)
                ORDER BY s.StartsOn
            ) AS nxt
    ORDER BY w.IsFeatured DESC, w.PriceMyr DESC;
END;
GO

/* ------------------------------------------------------------
   One workshop plus its full date list. Two result sets, one call.
   ------------------------------------------------------------ */
CREATE OR ALTER PROCEDURE dbo.usp_Workshop_GetBySlug
    @Slug VARCHAR(80)
AS
BEGIN
    SET NOCOUNT ON;

    IF @Slug IS NULL OR LTRIM(RTRIM(@Slug)) = ''
        THROW 50001, 'Slug is required.', 1;

    SELECT  w.Id, w.Slug, w.Code, w.Title, w.Summary, w.Description,
            w.Audience, w.Level, w.PriceMyr, w.PriceNote, w.DurationDays,
            w.IsFeatured, w.Accent
    FROM    dbo.Workshops AS w
    WHERE   w.Slug = @Slug;

    SELECT  s.Id, s.StartsOn, s.EndsOn, s.City, s.SeatsLeft
    FROM    dbo.WorkshopSessions AS s
    JOIN    dbo.Workshops AS w ON w.Id = s.WorkshopId
    WHERE   w.Slug = @Slug
    ORDER BY s.StartsOn;
END;
GO

/* ------------------------------------------------------------
   Insert an enquiry. Validation lives here as well as in the
   application, because the database is the last line of defence.
   Returns the generated reference so the caller can show it.
   ------------------------------------------------------------ */
CREATE OR ALTER PROCEDURE dbo.usp_Enquiry_Insert
    @PersonName NVARCHAR(80),
    @Email      NVARCHAR(200),
    @Phone      NVARCHAR(30)  = NULL,
    @WorkshopId INT           = NULL,
    @Message    NVARCHAR(1200),
    @NewId      UNIQUEIDENTIFIER OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @PersonName = LTRIM(RTRIM(ISNULL(@PersonName, N'')));
    SET @Email      = LTRIM(RTRIM(ISNULL(@Email, N'')));
    SET @Message    = LTRIM(RTRIM(ISNULL(@Message, N'')));

    IF LEN(@PersonName) = 0
        THROW 50010, 'Name is required.', 1;

    IF @Email NOT LIKE '%_@_%._%'
        THROW 50011, 'A valid email address is required.', 1;

    IF LEN(@Message) < 10
        THROW 50012, 'Message must be at least 10 characters.', 1;

    -- A workshop id that does not exist is treated as "no preference"
    -- rather than rejected, so a stale link never blocks a real enquiry.
    IF @WorkshopId IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM dbo.Workshops WHERE Id = @WorkshopId)
        SET @WorkshopId = NULL;

    BEGIN TRANSACTION;

    -- Id is a UNIQUEIDENTIFIER generated by NEWSEQUENTIALID(), so SCOPE_IDENTITY()
    -- does not apply. Capture the generated key with OUTPUT instead.
    DECLARE @inserted TABLE (Id UNIQUEIDENTIFIER);

    INSERT INTO dbo.Enquiries (PersonName, Email, Phone, WorkshopId, Message, Source)
    OUTPUT inserted.Id INTO @inserted (Id)
    VALUES (@PersonName, @Email, NULLIF(@Phone, N''), @WorkshopId, @Message, 'web');

    SET @NewId = (SELECT Id FROM @inserted);

    COMMIT TRANSACTION;

    SELECT @NewId AS Reference;
END;
GO

/* ------------------------------------------------------------
   Recent enquiries for the internal dashboard.
   ------------------------------------------------------------ */
CREATE OR ALTER PROCEDURE dbo.usp_Enquiry_Recent
    @Take INT = 20
AS
BEGIN
    SET NOCOUNT ON;

    IF @Take IS NULL OR @Take < 1   SET @Take = 20;
    IF @Take > 200                  SET @Take = 200;

    SELECT TOP (@Take)
           e.Id,
           e.PersonName,
           e.Email,
           e.Phone,
           w.Title AS WorkshopTitle,
           e.Message,
           e.CreatedAt
    FROM   dbo.Enquiries AS e
    LEFT JOIN dbo.Workshops AS w ON w.Id = e.WorkshopId
    ORDER BY e.CreatedAt DESC;
END;
GO

/* ------------------------------------------------------------
   Showcase: set-based aggregate instead of a loop.
   ------------------------------------------------------------ */
CREATE OR ALTER PROCEDURE dbo.usp_Report_EnquiriesByWorkshop
AS
BEGIN
    SET NOCOUNT ON;

    SELECT  w.Code,
            w.Title,
            COUNT(e.Id)                                              AS TotalEnquiries,
            SUM(CASE WHEN e.CreatedAt >= DATEADD(DAY, -30, SYSUTCDATETIME())
                     THEN 1 ELSE 0 END)                              AS Last30Days,
            MAX(e.CreatedAt)                                         AS MostRecent
    FROM    dbo.Workshops AS w
    LEFT JOIN dbo.Enquiries AS e ON e.WorkshopId = w.Id
    GROUP BY w.Code, w.Title
    ORDER BY TotalEnquiries DESC, w.Code;
END;
GO
